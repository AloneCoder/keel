<?php

declare(strict_types=1);

namespace Keel\Discovery;

/**
 * Runs every registered discovery over the classes found in the configured directories.
 * With a cache file: in production the cache is used as is; in development it is reused
 * only while the scanned files are unchanged (count and newest mtime).
 */
final class Discoverer
{
    /** @var array<class-string<DiscoveryInterface>, DiscoveryInterface> */
    private array $discoveries = [];

    /**
     * @param list<string> $directories
     */
    public function __construct(
        private readonly array $directories,
        private readonly ?string $cacheFile = null,
        private readonly bool $checkFreshness = true,
        private readonly ClassScanner $scanner = new ClassScanner(),
    ) {}

    public function add(DiscoveryInterface $discovery): self
    {
        $this->discoveries[$discovery::class] = $discovery;

        return $this;
    }

    /**
     * @template T of DiscoveryInterface
     *
     * @param class-string<T> $class
     *
     * @return T
     */
    public function get(string $class): DiscoveryInterface
    {
        $discovery = $this->discoveries[$class] ?? throw new \LogicException(sprintf('Discovery "%s" is not registered', $class));
        if (!$discovery instanceof $class) {
            throw new \LogicException(sprintf('Discovery "%s" has an unexpected type', $class));
        }

        return $discovery;
    }

    /**
     * Fills every discovery, from cache when possible. Returns true when the cache was used.
     */
    public function run(): bool
    {
        $scan = null;
        if ($this->cacheFile !== null && is_file($this->cacheFile)) {
            $cached = self::readCache($this->cacheFile);
            if ($cached !== null) {
                $fresh = !$this->checkFreshness;
                if (!$fresh) {
                    $scan = $this->scanner->scan($this->directories);
                    $fresh = $scan['files'] === $cached['files'] && $scan['mtime'] === $cached['mtime'];
                }

                if ($fresh && $this->restore($cached['results'])) {
                    return true;
                }
            }
        }

        $scan ??= $this->scanner->scan($this->directories);
        foreach ($scan['classes'] as $class) {
            if (!class_exists($class) && !interface_exists($class) && !enum_exists($class)) {
                continue;
            }
            $reflection = new \ReflectionClass($class);
            foreach ($this->discoveries as $discovery) {
                $discovery->discover($reflection);
            }
        }

        if ($this->cacheFile !== null) {
            $this->writeCache($scan['files'], $scan['mtime']);
        }

        return false;
    }

    public function clearCache(): void
    {
        if ($this->cacheFile !== null && is_file($this->cacheFile)) {
            unlink($this->cacheFile);
        }
    }

    /**
     * @param array<string, array<mixed>> $results
     */
    private function restore(array $results): bool
    {
        foreach ($this->discoveries as $class => $discovery) {
            if (!isset($results[$class])) {
                return false;
            }
        }
        foreach ($this->discoveries as $class => $discovery) {
            $discovery->restore($results[$class]);
        }

        return true;
    }

    private function writeCache(int $files, int $mtime): void
    {
        assert($this->cacheFile !== null);
        $results = [];
        foreach ($this->discoveries as $class => $discovery) {
            $results[$class] = $discovery->result();
        }

        $directory = dirname($this->cacheFile);
        if (!is_dir($directory) && !mkdir($directory, 0o775, true) && !is_dir($directory)) {
            throw new \RuntimeException(sprintf('Cannot create directory "%s"', $directory));
        }

        $source = "<?php\n\n// Generated by " . self::class . ". Do not edit.\n\nreturn "
            . var_export(['files' => $files, 'mtime' => $mtime, 'results' => $results], true) . ";\n";
        $temporary = $directory . '/.' . basename($this->cacheFile) . '.' . bin2hex(random_bytes(4)) . '.tmp';
        if (file_put_contents($temporary, $source) === false || !rename($temporary, $this->cacheFile)) {
            @unlink($temporary);
            throw new \RuntimeException(sprintf('Cannot write discovery cache "%s"', $this->cacheFile));
        }
    }

    /**
     * @return array{files: int, mtime: int, results: array<string, array<mixed>>}|null
     */
    private static function readCache(string $file): ?array
    {
        /** @var mixed $data */
        $data = require $file;
        if (!is_array($data) || !is_int($data['files'] ?? null) || !is_int($data['mtime'] ?? null) || !is_array($data['results'] ?? null)) {
            return null;
        }

        /** @var array{files: int, mtime: int, results: array<string, array<mixed>>} $data */
        return $data;
    }
}
