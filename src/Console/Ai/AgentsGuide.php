<?php

declare(strict_types=1);

namespace Keel\Console\Ai;

use Keel\App\App;
use Keel\Config\HttpConfig;
use Keel\Config\ServicesConfig;
use Keel\Keel;
use Keel\Routing\Attribute\MiddlewareProvider;

/**
 * Builds AGENTS.md for a Keel application: the stack, the commands, the layout, the conventions
 * a coding agent must follow (worker mode above all) and a snapshot of this application's
 * middleware, providers and routes, with pointers to the framework docs installed in vendor/.
 *
 * @internal used by keel:ai:init
 *
 * @phpstan-import-type MiddlewareEntry from MiddlewareProvider
 */
final class AgentsGuide
{
    private const int MAX_ROUTES = 60;

    public function __construct(private readonly App $app) {}

    public function render(): string
    {
        $out = "# AGENTS.md\n\n"
            . "Guidance for coding agents working on this project. Generated by `keel:ai:init` from the\n"
            . "application itself; edit it freely, regenerate with `keel:ai:init --force`.\n\n";

        $out .= "## Stack\n\n"
            . sprintf("- PHP %s, Keel %s: a worker-first micro-framework on PSR-7/11/14/15/16/3 with\n", '8.4+', Keel::VERSION)
            . "  attribute routing and a compiled container.\n"
            . "- Runs under FrankenPHP or RoadRunner workers (one process serves thousands of requests) or php-fpm.\n"
            . sprintf("- Application code: namespace `%s\\` in `src/`.\n\n", $this->rootNamespace());

        $out .= "## Commands\n\n";
        $console = is_file($this->app->projectDir . '/bin/console') ? 'bin/console' : 'php bin/console';
        foreach ([
            'keel:routes' => 'list the routes',
            'keel:doctor' => 'check PHP, extensions, config, caches and the container',
            'keel:compile' => 'rebuild the production caches (run after adding classes when debug is off)',
            'keel:openapi' => 'print the OpenAPI document',
            'keel:make:controller Name' => 'scaffold a controller (also make:middleware, make:listener, make:command, make:policy, make:check, make:authenticator)',
            'keel:install <component>' => 'add a framework component (provider, middleware, config file)',
        ] as $command => $what) {
            $out .= sprintf("- `%s %s`: %s\n", $console, $command, $what);
        }
        foreach ([
            'vendor/bin/phpunit' => ['phpunit.xml', 'phpunit.xml.dist'],
            'vendor/bin/phpstan analyse' => ['phpstan.neon', 'phpstan.neon.dist'],
            'vendor/bin/php-cs-fixer fix' => ['.php-cs-fixer.php', '.php-cs-fixer.dist.php'],
        ] as $command => $files) {
            foreach ($files as $file) {
                if (is_file($this->app->projectDir . '/' . $file)) {
                    $out .= sprintf("- `%s` (%s)\n", $command, $file);
                    break;
                }
            }
        }

        $out .= "\n## Layout\n\n"
            . "- `config/*.php`: each file returns one config object (or a closure `fn(Env \$env, string \$projectDir)` returning it);\n"
            . "  services receive it by type. Environment variables are read here, through `Env`, nowhere else.\n"
            . "- `src/`: scanned by discovery. Controllers (methods with `#[Get]`, `#[Post]`, ...), services with container\n"
            . "  attributes, `#[Listener]` methods and `#[AsCommand]` commands are found without registration.\n"
            . "- `var/cache/<env>/`: generated route, discovery and container caches. Never edit them.\n\n";

        $out .= "## Conventions\n\n"
            . "- Routes are attributes on controller methods: `#[Get('/users/{id:\\d+}')]`, `#[Prefix]` on the class,\n"
            . "  `#[Middleware]`, `#[Auth('role')]`, `#[Can('ability')]`, `#[RateLimit]`, `#[CacheControl]`, `#[OutputCache]`,\n"
            . "  `#[Idempotent]`, `#[BodyLimit]`, `#[Deprecated]`.\n"
            . "- Handler arguments: route placeholders by name (cast to the declared type), `#[FromBody]` / `#[FromQuery]` DTOs\n"
            . "  validated by attributes from `Keel\\Validation` (`NotBlank`, `Length`, `Range`, `Email`, ...), `Input`, the PSR-7\n"
            . "  request, services by type.\n"
            . "- Return an array or object (JSON), a string (HTML), null (204), `Redirect`, `EventStream` (Server-Sent Events)\n"
            . "  or a PSR-7 response. Throw `Keel\\Http\\Exception\\*` (`NotFoundException`, `ConflictException`, ...) for errors:\n"
            . "  they become RFC 9457 Problem Details.\n"
            . "- Worker mode: a service instance lives for the whole worker. Keep no request state in statics, globals or\n"
            . "  shared services; implement `Keel\\Container\\Resettable` where a service must hold per-request state; pass\n"
            . "  the request explicitly. Use `#[Transient]` for services that must be fresh on every `get()`.\n"
            . "- Work after the response (mails, webhooks) goes through `Keel\\Kernel\\DeferredTasks::defer()`\n"
            . "  (`Keel\\Mail\\Mailer::defer()` for a Symfony Mime `Email`); there is no queue.\n"
            . "- Tests use `Keel\\Testing\\TestClient::forApp(App::boot(\$projectDir, new Env(['APP_ENV' => 'test', 'APP_DEBUG' => '1'])))`\n"
            . "  and assert on `TestResponse` (`assertStatus`, `assertJson`, `assertProblem`, ...).\n\n";

        $out .= "## This application\n\n";
        $out .= sprintf("- Environment `%s`, debug %s.\n", $this->app->config->env, $this->app->config->debug ? 'on' : 'off');
        $http = $this->app->configs[HttpConfig::class] ?? null;
        $middleware = $http instanceof HttpConfig ? array_map(self::entry(...), $http->middleware) : [];
        $out .= '- Global middleware, in order: ' . ($middleware === [] ? 'none' : '`' . implode('`, `', $middleware) . '`') . ".\n";
        $services = $this->app->configs[ServicesConfig::class] ?? null;
        $providers = $services instanceof ServicesConfig ? array_map(self::short(...), $services->providers) : [];
        $out .= '- Service providers: ' . ($providers === [] ? 'none' : '`' . implode('`, `', $providers) . '`') . ".\n";
        $configs = array_map(self::short(...), array_keys($this->app->configs));
        sort($configs);
        $out .= '- Config objects: `' . implode('`, `', $configs) . "`.\n";
        $commands = array_keys($this->app->commands());
        if ($commands !== []) {
            $out .= '- Application commands: `' . implode('`, `', $commands) . "`.\n";
        }

        $routes = $this->app->router->routes();
        $out .= sprintf("\nRoutes (%d):\n\n", count($routes));
        foreach (array_slice($routes, 0, self::MAX_ROUTES) as $route) {
            $out .= sprintf("- `%s %s` -> `%s::%s`\n", implode('|', $route->methods), $route->path, self::short($route->handler[0]), $route->handler[1]);
        }
        if (count($routes) > self::MAX_ROUTES) {
            $out .= sprintf("- ... %d more: run `%s keel:routes`\n", count($routes) - self::MAX_ROUTES, $console);
        }

        $docs = $this->docs();
        if ($docs !== []) {
            $out .= "\n## Framework reference\n\nThe Keel documentation is installed with the framework; read the page before using a feature:\n\n";
            foreach ($docs as $path => $title) {
                $out .= sprintf("- `%s`: %s\n", $path, $title);
            }
        }

        return $out;
    }

    /**
     * The PSR-4 namespace mapped to src/ in composer.json, or "App".
     */
    private function rootNamespace(): string
    {
        $file = $this->app->projectDir . '/composer.json';
        /** @var mixed $data */
        $data = is_file($file) ? json_decode((string) file_get_contents($file), true) : null;
        $psr4 = is_array($data) && is_array($data['autoload'] ?? null) ? ($data['autoload']['psr-4'] ?? null) : null;
        foreach (is_array($psr4) ? $psr4 : [] as $namespace => $directory) {
            if (is_string($namespace) && is_string($directory) && rtrim($directory, '/') === 'src') {
                return rtrim($namespace, '\\');
            }
        }

        return 'App';
    }

    /**
     * Framework doc pages relative to the project, with their first heading.
     *
     * @return array<string, string>
     */
    private function docs(): array
    {
        $directory = dirname((string) new \ReflectionClass(Keel::class)->getFileName(), 2) . '/docs/en';
        $files = is_dir($directory) ? (scandir($directory) ?: []) : [];
        $docs = [];
        foreach ($files as $file) {
            if (!str_ends_with($file, '.md')) {
                continue;
            }
            $path = $directory . '/' . $file;
            $first = (string) strtok((string) file_get_contents($path), "\n");
            $docs[self::relative($this->app->projectDir, $path)] = trim(ltrim($first, '# '));
        }

        return $docs;
    }

    private static function relative(string $base, string $path): string
    {
        $base = rtrim((string) realpath($base), '/') . '/';
        $real = (string) realpath($path);

        return str_starts_with($real, $base) ? substr($real, strlen($base)) : $real;
    }

    /**
     * @param MiddlewareEntry $entry
     */
    private static function entry(string|array $entry): string
    {
        return self::short(is_string($entry) ? $entry : $entry[0]);
    }

    private static function short(string $class): string
    {
        $position = strrpos($class, '\\');

        return $position === false ? $class : substr($class, $position + 1);
    }
}
