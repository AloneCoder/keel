<?php

declare(strict_types=1);

namespace Keel\Console\Command;

use Keel\App\App;
use Nyholm\Psr7\ServerRequest;
use Nyholm\Psr7Server\ServerRequestCreator;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;

/**
 * Writes var/cache/ENV/preload.php for opcache.preload: every file the application loads to
 * boot and answer a request, in load order. With preloading those classes (including the
 * trait-based PSR-7 messages, which opcache cannot share otherwise) are linked once in shared
 * memory instead of once per php-fpm request or per worker.
 */
#[AsCommand(name: 'keel:preload', description: 'Generate an opcache.preload script from the files a request loads')]
final class PreloadCommand extends Command
{
    public function __construct(private readonly App $app)
    {
        parent::__construct();
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $path = $this->app->config->cacheDir() . '/preload.php';
        $files = self::files($this->app);
        $source = "<?php\n\n// Generated by keel:preload. Set opcache.preload to this file.\n\n"
            . "require_once " . var_export(self::autoloader(), true) . ";\n\n"
            . "foreach ([\n";
        foreach ($files as $file) {
            $source .= '    ' . var_export($file, true) . ",\n";
        }
        $source .= "] as \$file) {\n    require_once \$file;\n}\n";

        $directory = dirname($path);
        if (!is_dir($directory) && !mkdir($directory, 0o775, true) && !is_dir($directory)) {
            throw new \RuntimeException(sprintf('Cannot create directory "%s"', $directory));
        }
        if (file_put_contents($path, $source) === false) {
            throw new \RuntimeException(sprintf('Cannot write "%s"', $path));
        }

        $output->writeln(sprintf('<info>written</info> %s (%d files)', $path, count($files)));
        $output->writeln('Add to php.ini: opcache.preload=' . $path);

        return Command::SUCCESS;
    }

    /**
     * Files loaded by the application: boot already happened, so the list is every included
     * file minus the console's own, plus what a synthetic request and the SAPI request creator load.
     *
     * @return list<string>
     */
    public static function files(App $app): array
    {
        $app->kernel->handle(new ServerRequest('GET', '/__keel_preload__'));
        $app->kernel->terminate();
        class_exists(ServerRequestCreator::class);
        class_exists(\Nyholm\Psr7\UploadedFile::class);
        class_exists(\Nyholm\Psr7\Uri::class);

        $files = [];
        foreach (get_included_files() as $file) {
            if (self::isPreloadable($file, $app->projectDir)) {
                $files[] = $file;
            }
        }

        return $files;
    }

    private static function isPreloadable(string $file, string $projectDir): bool
    {
        $normalized = str_replace('\\', '/', $file);
        foreach (['/vendor/composer/', '/vendor/symfony/console/', '/vendor/phpunit/', '/vendor/bin/', '/bin/', '/tests/'] as $skip) {
            if (str_contains($normalized, $skip)) {
                return false;
            }
        }
        if (str_ends_with($normalized, '/preload.php') || str_contains($normalized, '/Console/')) {
            return false;
        }

        return str_contains($normalized, '/vendor/')
            || str_contains($normalized, '/src/')
            || str_starts_with($normalized, str_replace('\\', '/', $projectDir) . '/');
    }

    private static function autoloader(): string
    {
        foreach (get_included_files() as $file) {
            if (str_ends_with($file, '/vendor/autoload.php')) {
                return $file;
            }
        }

        throw new \RuntimeException('Composer autoloader not found among included files');
    }
}
