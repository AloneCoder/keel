<?php

declare(strict_types=1);

namespace Keel\Http;

/**
 * A handler return value Responder turns into a redirect: return Redirect::to('/login') or
 * Redirect::route('users.show', ['id' => 5], 303). The default status is 302; use 303 after a
 * POST so the browser follows with GET, 307/308 to keep the method, 301 for a permanent move.
 */
final readonly class Redirect
{
    /**
     * @param array<string, scalar|\Stringable|null> $params
     */
    private function __construct(
        public ?string $location,
        public ?string $routeName,
        public array $params,
        public int $status,
    ) {
        if ($status < 300 || $status > 399) {
            throw new \InvalidArgumentException(sprintf('A redirect needs a 3xx status, got %d', $status));
        }
    }

    public static function to(string $location, int $status = 302): self
    {
        return new self($location, null, [], $status);
    }

    /**
     * A redirect to a named route; the path is generated by the Router when the response is built.
     *
     * @param array<string, scalar|\Stringable|null> $params
     */
    public static function route(string $name, array $params = [], int $status = 302): self
    {
        return new self(null, $name, $params, $status);
    }
}
