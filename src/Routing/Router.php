<?php

declare(strict_types=1);

namespace Keel\Routing;

use Keel\Routing\Exception\RoutingException;

/**
 * Facade: builds, caches, matches and generates. In production load it from the cache file
 * written by write(); in development build it from controllers on every request.
 */
final class Router
{
    private readonly Matcher $matcher;

    private readonly UrlGenerator $generator;

    public function __construct(public readonly CompiledRoutes $compiled)
    {
        $this->matcher = new Matcher($compiled);
        $this->generator = new UrlGenerator($compiled);
    }

    /**
     * @param class-string ...$controllers
     */
    public static function fromControllers(string ...$controllers): self
    {
        return self::fromRoutes(new RouteCollector()->addControllers(...$controllers)->routes());
    }

    /**
     * @param list<Route> $routes
     */
    public static function fromRoutes(array $routes): self
    {
        return new self(new RouteCompiler()->compile($routes));
    }

    public static function fromCache(string $path): self
    {
        if (!is_file($path)) {
            throw new RoutingException(sprintf('Route cache "%s" does not exist', $path));
        }

        /** @var mixed $data */
        $data = require $path;
        if (!is_array($data) || !isset($data['routes'], $data['static'], $data['dynamic'], $data['names'])) {
            throw new RoutingException(sprintf('Route cache "%s" is malformed', $path));
        }

        /** @phpstan-ignore argument.type (the cache file is produced by write()) */
        return new self(CompiledRoutes::fromArray($data));
    }

    /**
     * Writes the compiled tables as a PHP file returning an array (atomic rename).
     */
    public function write(string $path): void
    {
        $directory = dirname($path);
        if (!is_dir($directory) && !mkdir($directory, 0o775, true) && !is_dir($directory)) {
            throw new RoutingException(sprintf('Cannot create directory "%s"', $directory));
        }

        $source = "<?php\n\n// Generated by " . self::class . ". Do not edit.\n\nreturn "
            . var_export($this->compiled->toArray(), true) . ";\n";
        $temporary = $directory . '/.' . basename($path) . '.' . bin2hex(random_bytes(4)) . '.tmp';
        if (file_put_contents($temporary, $source) === false || !rename($temporary, $path)) {
            @unlink($temporary);
            throw new RoutingException(sprintf('Cannot write route cache to "%s"', $path));
        }
    }

    public function match(string $method, string $path): MatchResult
    {
        return $this->matcher->match($method, $path);
    }

    /**
     * @param array<string, scalar|\Stringable|null> $params
     */
    public function generate(string $name, array $params = []): string
    {
        return $this->generator->generate($name, $params);
    }

    /** @return list<Route> */
    public function routes(): array
    {
        return $this->compiled->routes;
    }
}
